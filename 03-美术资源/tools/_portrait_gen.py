def safe_name(n):
    return re.sub(r'[\\/:*?"<>|]', '_', n)


def targets(heroes, pilot=False):
    have = set(os.path.splitext(f)[0] for f in os.listdir(SPR) if f.endswith('.png'))
    out = []
    for hid, h in heroes.items():
        name = str(h.get('name', ''))
        if not name or name == '无' or h.get('is_dummy'):
            continue
        if pilot:
            if name not in PILOT_NAMES:
                continue
        if str(hid) in have:
            continue
        raw_path = os.path.join(RAW, '%d_%s.png' % (hid, safe_name(name)))
        if os.path.exists(raw_path):
            continue
        out.append((hid, h, raw_path))
    out.sort(key=lambda t: t[0])
    return out


def fetch_one(hid, h, raw_path, retries=3):
    url = API + '?prompt=' + urllib.parse.quote(build_prompt(h)) + '&image_size=' + IMG_SIZE
    delay = 6
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
            with urllib.request.urlopen(req, timeout=180) as r:
                data = r.read()
            im = Image.open(io.BytesIO(data)).convert('RGBA')
            tmp = raw_path + '.tmp'
            im.save(tmp, 'PNG')
            os.replace(tmp, raw_path)
            return hid, h['name'], None, im.size
        except Exception as e:
            err = '%s: %s' % (type(e).__name__, e)
            if attempt < retries - 1:
                time.sleep(delay * (attempt + 1))
            else:
                return hid, h['name'], err, None


def run(pilot, workers):
    os.makedirs(RAW, exist_ok=True)
    heroes = load_heroes()
    todo = targets(heroes, pilot=pilot)
    print('待生成: %d 张（workers=%d, size=%s）' % (len(todo), workers, IMG_SIZE))
    if not todo:
        return
    t0 = time.time()
    ok = fail = 0
    failures = []
    with ThreadPoolExecutor(max_workers=workers) as ex:
        futs = {ex.submit(fetch_one, hid, h, rp): (hid, h['name']) for hid, h, rp in todo}
        for i, fut in enumerate(as_completed(futs), 1):
            hid, name, err, size = fut.result()
            if err:
                fail += 1
                failures.append({'id': hid, 'name': name, 'err': err})
                print('[%d/%d] FAIL %d %s -> %s' % (i, len(todo), hid, name, err[:80]))
            else:
                ok += 1
                print('[%d/%d] OK   %d %s %s (%.1fs)'
                      % (i, len(todo), hid, name, size, time.time() - t0), flush=True)
    with open(os.path.join(RAW, '_failures.json'), 'w', encoding='utf-8') as f:
        json.dump(failures, f, ensure_ascii=False, indent=2)
    print('完成：成功 %d / 失败 %d / 用时 %.1f 分钟' % (ok, fail, (time.time() - t0) / 60))
    if failures:
        print('失败清单：AI源图/npcs/_failures.json（重跑本命令即可续传）')


def make_sheet():
    names = PILOT_NAMES
    heroes = load_heroes()
    inv = {h['name']: hid for hid, h in heroes.items()}
    cell_w, cell_h = 240, 360
    cols = 4
    rows = (len(names) + cols - 1) // cols
    sheet = Image.new('RGB', (cols * cell_w, rows * cell_h), 'white')
    d = ImageDraw.Draw(sheet)
    for i, nm in enumerate(names):
        hid = inv.get(nm)
        p = os.path.join(SPR, '%d.png' % hid) if hid else ''
        x, y = (i % cols) * cell_w, (i // cols) * cell_h
        if hid and os.path.exists(p):
            im = Image.open(p).convert('RGBA')
            scale = (cell_h - 40) / im.height
            im = im.resize((int(im.width * scale), cell_h - 40), Image.LANCZOS)
            sheet.paste(im, (x + (cell_w - im.width) // 2, y + 26), im)
        else:
            d.text((x + 20, y + 120), '缺失:%s' % nm, fill='red')
        d.rectangle([x, y, x + cell_w - 1, y + cell_h - 1], outline=(180, 180, 180))
        d.text((x + 8, y + 6), '%d %s' % (hid or -1, nm), fill='black')
    sheet.save(SHEET_OUT)
    print('对照图:', SHEET_OUT)


