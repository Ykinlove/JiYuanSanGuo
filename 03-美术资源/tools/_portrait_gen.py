def load_heroes():
    heroes = {int(h['id']): h for h in json.load(
        open(os.path.join(DATA, 'heroes6.json'), encoding='utf-8'))}
    return heroes


def age_band(h):
    b = h.get('born_year', 0) or 0
    a = 195 - b
    if a < 0 or a > 80:
        a = 25
    if a <= 22:
        return '少年'
    if a <= 34:
        return '青年'
    if a <= 52:
        return '中年'
    return '老年'


def weapon_hint(h):
    ls = h.get('life_skills') or {}
    if ls.get('枪术', 0) >= 3000:
        return '手持红缨长枪'
    if ls.get('剑术', 0) >= 3000:
        return '腰佩长剑'
    if ls.get('射术', 0) >= 3000:
        return '背负长弓与箭壶'
    if ls.get('钝器', 0) >= 3000:
        return '手持长柄大刀'
    if ls.get('骑术', 0) >= 4000:
        return '腰佩弯刀、作骑马民族装束'
    return ''


