def build():
    out = []
    for (hid, name, style, born, died, origin, faction, rarity,
         lead, might, intel, pol, traits, bio) in HEROES:
        out.append({
            "id": hid,
            "name": name,
            "style": style,
            "born": born,
            "died": died,
            "origin": origin,
            "faction": faction,
            "faction_name": FACTIONS.get(faction, faction),
            "rarity": rarity,
            "traits": traits,
            "bio": bio,
            "leadership": lead,
            "might": might,
            "intellect": intel,
            "politics": pol,
            "recruitable": faction in ("neutral", "nanman"),
            "relations": [],
        })

    by_id = {h["id"]: h for h in out}
    for (a, kind, b, desc) in RELATIONS:
        if a in by_id and b in by_id:
            by_id[a]["relations"].append({
                "type": kind, "target": b, "desc": desc,
            })
    return out


def main():
    heroes = build()
    with open(os.path.join(DATA, "characters.json"), "w", encoding="utf-8") as f:
        json.dump(heroes, f, ensure_ascii=False, indent=2)

    print("人物 %d 位" % len(heroes))
    fa = {}
    for h in heroes:
        fa[h["faction_name"]] = fa.get(h["faction_name"], 0) + 1
    print("阵营分布:", fa)
    rel = sum(len(h["relations"]) for h in heroes)
    print("关系网 %d 条" % rel)
    # 校验关系目标都存在
    ids = {h["id"] for h in heroes}
    bad = []
    for h in heroes:
        for r in h["relations"]:
            if r["target"] not in ids:
                bad.append("%s -> %s" % (h["id"], r["target"]))
    print("悬空关系:", bad if bad else "无")


if __name__ == "__main__":
    main()
